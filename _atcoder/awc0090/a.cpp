#define debug(x) cout << #x << " is " << x << endl;
const long long INF = 1e18;


void solve() {
    int n; cin >> n;
    ll ans = 0ll;
    for(int i = 0; i < n; i++) {
        ll x, y;
        cin >> x >> y;
        ans += max(0ll, x - y);
    }
    cout << ans << endl;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    // cin >> t;
    while (t--) {
        solve();
    }
    
}
